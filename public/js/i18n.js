// ── i18n Manager ──────────────────────────────────────────────
class I18n {
    constructor() {
        this.currentLang = localStorage.getItem('app-language') || 'en';
    }

    t(key) {
        return translations[this.currentLang]?.[key] || translations.en[key] || key;
    }

    setLanguage(lang) {
        if (translations[lang]) {
            this.currentLang = lang;
            localStorage.setItem('app-language', lang);
            this.updatePage();
        }
    }

    getLanguage() {
        return this.currentLang;
    }

    updatePage() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translated = this.t(key);
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translated;
            } else if (el.tagName === 'OPTION') {
                el.textContent = translated;
            } else {
                // Preserve child elements (like badges etc)
                const childElements = el.querySelectorAll('*');
                if (childElements.length === 0) {
                    el.textContent = translated;
                } else {
                    // Find the first text node and update it
                    for (const node of el.childNodes) {
                        if (node.nodeType === Node.TEXT_NODE && node.textContent.trim()) {
                            node.textContent = translated;
                            break;
                        }
                    }
                }
            }
        });
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            el.title = this.t(el.getAttribute('data-i18n-title'));
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            el.placeholder = this.t(el.getAttribute('data-i18n-placeholder'));
        });
        // Dispatch event for dynamic content listeners
        window.dispatchEvent(new CustomEvent('language-changed', { detail: { lang: this.currentLang } }));
    }
}

window.i18n = new I18n();
